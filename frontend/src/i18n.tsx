export const locales = {
  fr: { label: 'Français', dir: 'ltr' as const, strings: fr as Dictionary },
  en: { label: 'English', dir: 'ltr' as const, strings: en },
}
export type Locale = keyof typeof locales

type I18n = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: StringKey, vars?: Record<string, string | number>) => string }
const I18nContext = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => (localStorage.getItem('eih-locale') as Locale) || 'fr')
  useEffect(() => {
    localStorage.setItem('eih-locale', locale)
    document.documentElement.lang = locale
    document.documentElement.dir = locales[locale].dir
  }, [locale])
  const value = useMemo<I18n>(() => ({
    locale,
    setLocale,
    t: (key, vars) => {
      let text = locales[locale].strings[key] ?? key
      for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, String(value))
      return text
    },
  }), [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useT() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useT must be used inside I18nProvider')
  return context
}
